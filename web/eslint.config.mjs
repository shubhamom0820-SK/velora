import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

// CLAUDE.md rule 14: server data reaches components only through the api client
// and the query hooks in src/lib/, never a stray fetch (T-1.18). The same holds
// for XMLHttpRequest, the photo upload's transport since T-4.6 (src/lib/upload.ts),
// and WebSocket, the app's one socket since T-7.12 (src/lib/ws.ts): a request
// is made in src/lib or not at all.
const NO_FETCH =
  "Server data goes through src/lib: the api client and the TanStack Query hooks in src/lib/queries (CLAUDE.md rule 14).";
const TRANSPORTS = ["fetch", "XMLHttpRequest", "WebSocket"];

// zod only through src/lib/zod.ts, or zod/mini through src/lib/zod-mini.ts,
// both of which turn its eval probe off: production's CSP reports the probe as
// a violation (T-3.11). Anchored, so `zod/mini` and `zod/v4` are caught too
// (T-9.10).
const ZOD = {
  regex: "^zod(/|$)",
  message:
    "Import z from @/lib/zod, or @/lib/zod-mini on the (app) pages (T-9.10): both set jitless, since production's CSP reports zod's eval probe (T-3.11).",
};

// The Firebase SDK only through src/lib/firebase.ts (T-3.14): it loads the SDK
// on demand, so only a Firebase build's sign-in screen downloads it, and it
// keeps Firebase's user in memory, signed out after the exchange (D-085).
const FIREBASE = {
  // Anchored: a bare "firebase" pattern is gitignore-style, and would also
  // match our own @/lib/firebase.
  regex: "^@?firebase(/|$)",
  message:
    "Use @/lib/firebase, which loads the SDK on demand and keeps Firebase's user in memory (T-3.14).",
};

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  {
    files: ["src/**/*.{js,jsx,mjs,ts,tsx}"],
    ignores: ["src/lib/**"],
    rules: {
      "no-restricted-globals": [
        "error",
        ...TRANSPORTS.map((name) => ({ name, message: NO_FETCH })),
      ],
      "no-restricted-properties": [
        "error",
        ...["window", "globalThis", "self"].flatMap((object) =>
          TRANSPORTS.map((property) => ({
            object,
            property,
            message: NO_FETCH,
          })),
        ),
      ],
    },
  },
  // Each library that must come through one module of ours (T-3.11, T-3.14).
  // One rule for both: flat config replaces a rule's options rather than adding
  // to them, so two blocks would leave the later one's ban alone in force.
  {
    files: ["src/**/*.{js,jsx,mjs,ts,tsx}"],
    ignores: ["src/lib/zod.ts", "src/lib/zod-mini.ts", "src/lib/firebase.ts"],
    rules: {
      "no-restricted-imports": ["error", { patterns: [ZOD, FIREBASE] }],
    },
  },
  {
    files: ["src/lib/zod.ts", "src/lib/zod-mini.ts"],
    rules: { "no-restricted-imports": ["error", { patterns: [FIREBASE] }] },
  },
  {
    files: ["src/lib/firebase.ts"],
    rules: { "no-restricted-imports": ["error", { patterns: [ZOD] }] },
  },
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated by `make types`; never edited by hand.
    "src/types/api.ts",
  ]),
]);

export default eslintConfig;
