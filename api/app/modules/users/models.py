"""`users` — 03-SCHEMA.md §1.

gender and dob are immutable once set; a database trigger enforces it
(migration T-1.9), and T-3.6 maps its `check_violation` to IMMUTABLE_FIELD.
"""

from __future__ import annotations

import uuid
from datetime import date, datetime

from sqlalchemy import (
    Boolean,
    Date,
    DateTime,
    Index,
    LargeBinary,
    SmallInteger,
    Text,
    false,
    text,
)
from sqlalchemy.dialects.postgresql import CITEXT
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base, Timestamps, pg_enum, uuid_pk
from app.core.enums import Gender, OnboardingStep, Role, UserStatus


class User(Timestamps, Base):
    __tablename__ = "users"

    id: Mapped[uuid.UUID] = uuid_pk()
    phone_hash: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    phone_enc: Mapped[bytes] = mapped_column(LargeBinary, nullable=False)
    gender: Mapped[Gender | None] = mapped_column(pg_enum(Gender))
    dob: Mapped[date | None] = mapped_column(Date)
    role: Mapped[Role] = mapped_column(
        pg_enum(Role), nullable=False, server_default=Role.USER.value
    )
    status: Mapped[UserStatus] = mapped_column(
        pg_enum(UserStatus), nullable=False, server_default=UserStatus.ACTIVE.value
    )
    onboarding_step: Mapped[OnboardingStep] = mapped_column(
        pg_enum(OnboardingStep),
        nullable=False,
        server_default=OnboardingStep.DOB.value,
    )
    is_verified: Mapped[bool] = mapped_column(
        Boolean, nullable=False, server_default=false()
    )
    pin_hash: Mapped[str | None] = mapped_column(Text)
    pin_failed: Mapped[int] = mapped_column(
        SmallInteger, nullable=False, server_default=text("0")
    )
    # Generated by the app at signup (T-3.3): human-friendly, collision-retried.
    referral_code: Mapped[str] = mapped_column(CITEXT, nullable=False, unique=True)
    last_active_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    deleted_requested_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True)
    )

    __table_args__ = (
        Index("ix_users_status_last_active_at", "status", last_active_at.desc()),
    )
